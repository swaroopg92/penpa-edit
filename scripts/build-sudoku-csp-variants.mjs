import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const variantsRoot = path.join(repositoryRoot, "docs", "js", "sudoku_csp_variants");
const descriptorsRoot = path.join(repositoryRoot, "docs", "js", "sudoku_variants");
const workerOutputRoot = path.join(repositoryRoot, "generated", "workers");
const require = createRequire(import.meta.url);
const standaloneSources = [
    "anti_king.js",
    "anti_knight.js",
    "chess_kings.js",
    "knightmare.js",
    "disparity.js",
    "dutch_flat_mates.js",
    "non_consecutive.js",
    "diagonal_non_consecutive.js",
    "no_even_neighbours.js",
    "no_three_in_row.js",
    "queen_digits.js",
    "pirate_cells.js",
    "touchy_cells.js",
    "odd_even_sums.js",
    "sequence_top_bottom.js",
];
const relationDirectories = [
    "cell_relations",
    "edge_relations",
    "directional_marks",
    "catalog_lines",
    "quad_relations",
    "outside_relations"
];
const standaloneDirectories = [
    "cage_constraints",
    "region_constraints",
    "line_constraints"
];

async function relationSources(directory) {
    const entries = await readdir(path.join(variantsRoot, directory));
    const validators = entries.filter((entry) => entry.endsWith(".js") &&
        entry !== "family.js" && entry !== "index.js").sort();
    return [
        `${directory}/family.js`,
        ...validators.map((entry) => `${directory}/${entry}`)
    ];
}

const relationSourceGroups = await Promise.all(relationDirectories.map(relationSources));
const standaloneSourceGroups = await Promise.all(standaloneDirectories.map(async (directory) => {
    const entries = await readdir(path.join(variantsRoot, directory));
    return entries.filter((entry) => entry.endsWith(".js") && entry !== "index.js")
        .sort()
        .map((entry) => `${directory}/${entry}`);
}));
const sources = [
    ...standaloneSources,
    ...standaloneSourceGroups.flat(),
    "relation_family.js",
    ...relationSourceGroups.flat()
];

const modules = await Promise.all(sources.map(async (source) => {
    const contents = await readFile(path.join(variantsRoot, source), "utf8");
    return `// Source: ${source}\n${contents.trim()}`;
}));

const banner = [
    "// Generated by scripts/build-sudoku-csp-variants.mjs.",
    "// Edit the source modules, then run npm run build:csp-variants."
].join("\n");

await writeFile(path.join(variantsRoot, "browser.js"), `${banner}\n\n${modules.join("\n\n")}\n`);

const descriptorEntries = (await readdir(path.join(descriptorsRoot, "descriptors")))
    .filter((entry) => entry.endsWith(".js"))
    .sort();
const parserEntries = (await readdir(path.join(descriptorsRoot, "parsers")))
    .filter((entry) => entry.endsWith(".js"))
    .sort((first, second) => {
        const firstIsDescriptorFactory = first.endsWith("_descriptor.js");
        const secondIsDescriptorFactory = second.endsWith("_descriptor.js");
        return Number(firstIsDescriptorFactory) - Number(secondIsDescriptorFactory) ||
            first.localeCompare(second);
    });
const validatedRegistry = require(path.join(descriptorsRoot, "index.js"));
if (validatedRegistry.ids().length !== descriptorEntries.length) {
    throw new Error("Variant Registry discovery did not load every descriptor source.");
}
const descriptorSources = [
    await readFile(path.join(descriptorsRoot, "runtime.js"), "utf8"),
    await readFile(path.join(descriptorsRoot, "constraint_families.js"), "utf8"),
    ...await Promise.all(parserEntries.map((entry) =>
        readFile(path.join(descriptorsRoot, "parsers", entry), "utf8"))),
    ...await Promise.all(descriptorEntries.map((entry) =>
        readFile(path.join(descriptorsRoot, "descriptors", entry), "utf8")))
];
const descriptorBanner = [
    "// Generated by scripts/build-sudoku-csp-variants.mjs.",
    "// Edit sudoku_variants/runtime.js or descriptor sources, then run npm run build:csp-variants."
].join("\n");
const descriptorFooter = [
    "var SudokuVariantRegistry = SudokuVariantRuntime.createRegistry(SudokuVariantDescriptorSources, SudokuConstraintFamilySources);",
    "if (typeof window !== \"undefined\") window.SudokuVariantRegistry = SudokuVariantRegistry;"
].join("\n");
await writeFile(path.join(descriptorsRoot, "browser.js"),
    `${descriptorBanner}\n\n${descriptorSources.map((source) => source.trim()).join("\n\n")}\n\n${descriptorFooter}\n`);

const jsRoot = path.join(repositoryRoot, "docs", "js");
async function buildWorkerBundle(outputName, sourceNames) {
    const workerSources = await Promise.all(sourceNames.map((sourceName) =>
        readFile(path.join(jsRoot, sourceName), "utf8")));
    const workerBanner = [
        "// Generated by scripts/build-sudoku-csp-variants.mjs.",
        "// Self-contained worker: do not add runtime importScripts dependencies."
    ].join("\n");
    await mkdir(workerOutputRoot, { recursive: true });
    await writeFile(path.join(workerOutputRoot, outputName),
        `${workerBanner}\n\n${workerSources.map((source) => source.trim()).join("\n\n")}\n`);
}

await buildWorkerBundle("sudoku_solver_worker_bundle.js", [
    "sudoku_csp.js",
    "sudoku_csp_variants/browser.js",
    "sudoku_variants/browser.js",
    "sudoku_solver_worker_entry.js"
]);
await buildWorkerBundle("sudoku_generator_worker_bundle.js", [
    "sudoku_csp.js",
    "sudoku_csp_variants/browser.js",
    "sudoku_variants/browser.js",
    "sudoku_generator.js",
    "sudoku_generator_worker_entry.js"
]);
await Promise.all([
    rm(path.join(jsRoot, "sudoku_solver_worker_bundle.js"), { force: true }),
    rm(path.join(jsRoot, "sudoku_generator_worker_bundle.js"), { force: true })
]);
