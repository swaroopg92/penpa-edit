import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const variantsRoot = path.join(repositoryRoot, "docs", "js", "sudoku_csp_variants");
const standaloneSources = [
    "anti_king.js",
    "anti_knight.js",
    "chess_kings.js",
    "knightmare.js",
    "disparity.js",
    "non_consecutive.js",
    "diagonal_non_consecutive.js",
    "no_even_neighbours.js",
    "no_three_in_row.js",
    "queen_digits.js",
    "pirate_cells.js",
    "touchy_cells.js",
    "odd_even_sums.js",
    "sequence_top_bottom.js",
];
const relationDirectories = [
    "cell_relations",
    "edge_relations",
    "directional_marks",
    "catalog_lines",
    "quad_relations",
    "outside_relations"
];
const standaloneDirectories = [
    "cage_constraints",
    "region_constraints",
    "line_constraints"
];

async function relationSources(directory) {
    const entries = await readdir(path.join(variantsRoot, directory));
    const validators = entries.filter((entry) => entry.endsWith(".js") &&
        entry !== "family.js" && entry !== "index.js").sort();
    return [
        `${directory}/family.js`,
        ...validators.map((entry) => `${directory}/${entry}`)
    ];
}

const relationSourceGroups = await Promise.all(relationDirectories.map(relationSources));
const standaloneSourceGroups = await Promise.all(standaloneDirectories.map(async (directory) => {
    const entries = await readdir(path.join(variantsRoot, directory));
    return entries.filter((entry) => entry.endsWith(".js") && entry !== "index.js")
        .sort()
        .map((entry) => `${directory}/${entry}`);
}));
const sources = [
    ...standaloneSources,
    ...standaloneSourceGroups.flat(),
    "relation_family.js",
    ...relationSourceGroups.flat()
];

const modules = await Promise.all(sources.map(async (source) => {
    const contents = await readFile(path.join(variantsRoot, source), "utf8");
    return `// Source: ${source}\n${contents.trim()}`;
}));

const banner = [
    "// Generated by scripts/build-sudoku-csp-variants.mjs.",
    "// Edit the source modules, then run npm run build:csp-variants."
].join("\n");

await writeFile(path.join(variantsRoot, "browser.js"), `${banner}\n\n${modules.join("\n\n")}\n`);
